"""Generate a Mermaid lineage diagram from dbt's manifest (always in sync with the code)."""
from __future__ import annotations

import json
import os

ROOT = os.path.dirname(__file__)


def mermaid(manifest: dict) -> str:
    nodes = {k: v for k, v in manifest["nodes"].items() if v["resource_type"] == "model"}
    lines = ["flowchart LR", "  raw[(data/raw_snapshots.csv)]"]
    for uid, n in sorted(nodes.items()):
        deps = [d for d in n["depends_on"]["nodes"] if d in nodes]
        if not deps:
            lines.append(f"  raw --> {n['name']}")
        for d in sorted(deps):
            lines.append(f"  {nodes[d]['name']} --> {n['name']}")
    return "\n".join(lines)


def main() -> None:
    with open(os.path.join(ROOT, "target", "manifest.json"), encoding="utf-8") as fh:
        text = "# Lineage\n\nGenerated by `python lineage.py` from the dbt manifest.\n\n```mermaid\n" + mermaid(json.load(fh)) + "\n```\n"
    with open(os.path.join(ROOT, "LINEAGE.md"), "w", encoding="utf-8") as fh:
        fh.write(text)
    print(text)


if __name__ == "__main__":
    main()
