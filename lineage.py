"""Generate a Mermaid lineage diagram from dbt's manifest (always in sync with the code)."""
from __future__ import annotations

import json
import os
import argparse
import hashlib

ROOT = os.path.dirname(__file__)


def mermaid(manifest: dict) -> str:
    nodes = {k: v for k, v in manifest["nodes"].items() if v["resource_type"] == "model"}
    lines = ["flowchart LR", "  raw[(data/raw_snapshots.csv)]"]
    for uid, n in sorted(nodes.items()):
        deps = [d for d in n["depends_on"]["nodes"] if d in nodes]
        if not deps:
            lines.append(f"  raw --> {n['name']}")
        for d in sorted(deps):
            lines.append(f"  {nodes[d]['name']} --> {n['name']}")
    return "\n".join(lines)


def impact(manifest, model, column=None):
    """Conservative model-level impact, not inferred column-level SQL lineage."""
    nodes = {**manifest["nodes"], **manifest.get("exposures", {})}
    matches = [uid for uid, node in nodes.items() if node["resource_type"] == "model" and node["name"] == model]
    if len(matches) != 1:
        raise ValueError("Choose exactly one model from the current manifest")
    start = matches[0]
    if column and column not in nodes[start].get("columns", {}):
        raise ValueError("Column is not declared in that model's contract")
    affected = {start}
    while True:
        downstream = {uid for uid, node in nodes.items() if set(node.get("depends_on", {}).get("nodes", [])) & affected}
        expanded = affected | downstream
        if expanded == affected:
            break
        affected = expanded
    return {"model": model, "column": column, "granularity": "conservative model-level downstream impact",
            "limits": "Column is validated against the contract; every dependent model is included, even if it does not use that column.",
            "models": sorted(nodes[uid]["name"] for uid in affected if nodes[uid]["resource_type"] == "model"),
            "tests": sorted(nodes[uid]["name"] for uid in affected if nodes[uid]["resource_type"] == "test"),
            "consumers": sorted([{"name": nodes[uid]["name"], "url": nodes[uid].get("url"),
                                  "owner": nodes[uid].get("owner")} for uid in affected
                                 if nodes[uid]["resource_type"] == "exposure"], key=lambda item: item["name"])}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--impact", metavar="MODEL", help="Print downstream models, tests and published consumers")
    parser.add_argument("--column", help="Validate a changed column against the model contract")
    args = parser.parse_args()
    with open(os.path.join(ROOT, "target", "manifest.json"), encoding="utf-8") as fh:
        manifest_text = fh.read()
        manifest = json.loads(manifest_text)
    if args.impact:
        report = impact(manifest, args.impact, args.column)
        report["manifest_sha256"] = hashlib.sha256(manifest_text.encode()).hexdigest()
        print(json.dumps(report, indent=2))
        return
    if args.column:
        parser.error("--column requires --impact")
    text = "# Lineage\n\nGenerated by `python lineage.py` from the dbt manifest.\n\n```mermaid\n" + mermaid(manifest) + "\n```\n"
    with open(os.path.join(ROOT, "LINEAGE.md"), "w", encoding="utf-8") as fh:
        fh.write(text)
    print(text)


if __name__ == "__main__":
    main()
